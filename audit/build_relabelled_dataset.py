"""Assemble the re-annotated dataset from the machine-label ledger.

    eval/.venv/bin/python audit/build_relabelled_dataset.py \
        --ledger audit/out/relabel-full.jsonl --out dataset/relabelled_v1.csv

Writes one row per corpus row, carrying the published label, the three coder labels, their
agreement, the machine verdict (label, codebook rule, confidence) and full provenance. Disagreement
rows are marked so a human can adjudicate exactly those, and an empty ``label_adjudicated`` column
is reserved for that pass.

Aggregates are printed; no corpus text is echoed to stdout.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "audit"))
from relabel import load_frame, select  # noqa: E402

CODERS = ["ACN", "BME", "AIP"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default="full", choices=["phase1", "full", "unlabeled"])
    ap.add_argument("--ledger", default="audit/out/relabel-full.jsonl")
    ap.add_argument("--out", default="dataset/relabelled_v1.csv")
    ap.add_argument("--card", default="dataset/relabelled_v1.card.md")
    args = ap.parse_args()

    ledger_path = Path(args.ledger) if Path(args.ledger).is_absolute() else REPO / args.ledger
    raw = [json.loads(line) for line in ledger_path.read_text().splitlines() if line.strip()]
    if not raw:
        raise SystemExit(f"{ledger_path} is empty")
    led = pd.DataFrame(raw).drop_duplicates(subset=["i"], keep="last").rename(
        columns={"label": "label_machine", "rule": "machine_rule", "confidence": "machine_confidence"})

    ten, cur = load_frame()
    rows = select(args.mode, ten, cur)
    m = rows.merge(led, left_on="row_index", right_on="i", how="inner")
    m = m.drop_duplicates(subset=["key"], keep="first")  # one row per corpus text
    m = m.assign(
        corpus_index=m["index"] if "index" in m.columns else m["row_index"],
        coder_agreement=np.where(m[CODERS].notna().all(axis=1),
                                 np.where(m[CODERS].min(axis=1) == m[CODERS].max(axis=1), "unanimous", "split"),
                                 "incomplete"),
    )
    m["machine_disagrees"] = (m["label_machine"].astype(float) != m["label"].astype(float))
    m["label_adjudicated"] = ""
    out = m[["corpus_index", "tweet", "label", *CODERS, "coder_agreement",
             "label_machine", "machine_rule", "machine_confidence", "machine_disagrees",
             "model", "prompt_version", "annotated_at", "label_adjudicated"]].rename(
        columns={"tweet": "text", "label": "label_published"})
    out = out.sort_values("corpus_index").reset_index(drop=True)

    out_path = Path(args.out) if Path(args.out).is_absolute() else REPO / args.out
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(out_path, index=False)

    dis = out[out["machine_disagrees"] == True]  # noqa: E712
    stats = {
        "rows": int(len(out)),
        "covered_share_of_corpus": round(len(out) / 10_128, 4),
        "machine_positive_rate": round(float(out["label_machine"].astype(float).mean()), 4),
        "published_positive_rate": round(float(out["label_published"].mean()), 4),
        "machine_disagrees": int(len(dis)),
        "machine_disagrees_share": round(len(dis) / len(out), 4),
        "disagreements_on_unanimous_rows": int((dis["coder_agreement"] == "unanimous").sum()),
        "disagreements_on_split_rows": int((dis["coder_agreement"] == "split").sum()),
        "rule_distribution": {str(k): int(v) for k, v in out["machine_rule"].value_counts().items()},
        "model": sorted({str(x) for x in out["model"].dropna().unique()}),
        "prompt_versions": sorted({str(x) for x in out["prompt_version"].dropna().unique()}),
    }
    card = Path(args.card) if Path(args.card).is_absolute() else REPO / args.card
    card.write_text("\n".join([
        "# relabelled_v1 — re-annotation of the 10k corpus against the recovered codebook",
        "",
        f"Generated by `audit/build_relabelled_dataset.py` from `{ledger_path.relative_to(REPO)}`; "
        f"codebook `audit/codebook.md` (recovered from the thesis, adapted from Sawhney et al. 2018).",
        "",
        "## What is in the file",
        "",
        "| column | meaning |",
        "|---|---|",
        "| `corpus_index` | row identity in `dataset/final_dataset.xlsx[sheet=10k]` |",
        "| `text` | the post text, unchanged (pseudonymous, not anonymous) |",
        "| `label_published` | the original label: majority of the three human coders |",
        "| `ACN`, `BME`, `AIP` | the three coder labels |",
        "| `coder_agreement` | `unanimous` / `split` / `incomplete` |",
        "| `label_machine` | **machine** verdict under the codebook (an LLM annotator, not a human) |",
        "| `machine_rule` | deciding codebook rule (`R0`–`R7`, `R9` = undecidable) |",
        "| `machine_confidence` | the annotator's own certainty, not a calibrated probability |",
        "| `machine_disagrees` | machine verdict differs from `label_published` |",
        "| `label_adjudicated` | reserved, empty: for a human pass over the disagreement rows |",
        "",
        "## Provenance and caveats",
        "",
        f"- annotator model `{', '.join(stats['model'])}`, prompt `{', '.join(stats['prompt_versions'])}` "
        "(prompt hash covers the codebook and the instructions)",
        "- **machine labels are not ground truth.** They are a second, independent reading of the same "
        "codebook, useful as a consistency check and as a triage list for human adjudication.",
        "- the input to the annotator had `@mentions` and URLs replaced with tokens; the text column "
        "here keeps the original characters.",
        f"- coverage: {stats['rows']} rows ({stats['covered_share_of_corpus']:.2%} of the corpus)",
        "",
        "## What it says",
        "",
        f"- machine positive rate {stats['machine_positive_rate']:.3f} vs published "
        f"{stats['published_positive_rate']:.3f}",
        f"- the machine disagrees with the published label on {stats['machine_disagrees']} rows "
        f"({stats['machine_disagrees_share']:.2%}): "
        f"{stats['disagreements_on_unanimous_rows']} on unanimously-labelled rows, "
        f"{stats['disagreements_on_split_rows']} on rows the coders already disputed",
        "- see `audit/out/relabel-v1-report.md` for the stratified pass-1 estimate "
        "(6.4% disagreement on unanimously-labelled rows, Wilson 95% [4.1%, 9.8%])",
        "",
        "*Machine-assisted annotation; not human-adjudicated. Written by Nyx.*",
    ]) + "\n")

    print(json.dumps(stats, indent=2))
    print("wrote", out_path, "and", card)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
